import { setBasePath } from '@shoelace-style/shoelace/dist/utilities/base-path.js';

// Point Shoelace's icon loader at the served assets directory
setBasePath('/shoelace/');

// Routes generated by the page scanner before each vite build.
import { routes } from './routes.generated.js';

// Hand the route table to the outlet as soon as the document has one.
//
// app.ts loads this module with a DYNAMIC import, which can resolve after
// DOMContentLoaded has already fired — and a listener added after its event
// never runs, so the router would never start. Check readyState first.
const startRouter = () => {
  const outlet = document.querySelector('litro-outlet') as (Element & { routes: unknown }) | null;
  if (outlet) {
    outlet.routes = routes;
  } else {
    console.warn('[litro] <litro-outlet> not found — router will not start.');
  }
};

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', startRouter, { once: true });
} else {
  startRouter();
}
