#!/usr/bin/env node
/**
 * Regenerates the cross-framework benchmark table in README.md from
 * `benchmarks/results/latest.json`. Rewrites only the block between the
 * `<!-- BENCH:BEGIN -->` and `<!-- BENCH:END -->` markers; everything else
 * is preserved byte-for-byte.
 *
 * Run after `pnpm bench:cross` (the root `bench:cross` script chains this
 * automatically). Idempotent — running it without a benchmark refresh
 * produces no diff.
 */

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const JSON_PATH = resolve(ROOT, 'benchmarks/results/latest.json');
const README_PATH = resolve(ROOT, 'README.md');
const BEGIN = '<!-- BENCH:BEGIN -->';
const END = '<!-- BENCH:END -->';

function fmtMs(ms) {
  if (!Number.isFinite(ms)) return 'n/a';
  return ms >= 1000 ? `${(ms / 1000).toFixed(1)}s` : `${ms.toFixed(0)}ms`;
}

function fmtBytes(b) {
  if (!Number.isFinite(b)) return 'n/a';
  return b >= 1024 ? `${(b / 1024).toFixed(1)} KB` : `${b} B`;
}

/**
 * Average gzip page weight across routes that returned 200.
 * Returns NaN when no routes succeeded — picks downstream skip NaN, so a
 * framework whose every route 404'd cannot be crowned the page-weight winner.
 */
function avgPageWeight(pageWeight) {
  const live = Object.values(pageWeight ?? {}).filter((r) => r.statusCode === 200);
  if (live.length === 0) return NaN;
  return live.reduce((sum, r) => sum + r.gzipBytes, 0) / live.length;
}

/** Returns the index of the lowest finite value, or -1 if no value is finite. */
function pickLowest(values, lowerIsBetter = true) {
  let bestIdx = -1;
  for (let i = 0; i < values.length; i++) {
    if (!Number.isFinite(values[i])) continue;
    if (bestIdx === -1) {
      bestIdx = i;
      continue;
    }
    if (lowerIsBetter ? values[i] < values[bestIdx] : values[i] > values[bestIdx]) {
      bestIdx = i;
    }
  }
  return bestIdx;
}

function bold(s, isWinner) {
  return isWinner ? `**${s}**` : s;
}

function renderTable(crossFramework, meta) {
  // Preserve the column order expected by the README: Litro, Next.js, Nuxt.
  const order = ['litro', 'nextjs', 'nuxt'];
  const fws = order
    .map((name) => crossFramework.find((f) => f.name === name))
    .filter(Boolean);

  if (fws.length === 0) {
    throw new Error('latest.json has no crossFramework entries');
  }

  const labels = { litro: 'Litro', nextjs: 'Next.js', nuxt: 'Nuxt' };
  const headerNames = fws.map((f) => `${labels[f.name]} (v${f.version})`);

  const buildMedians = fws.map((f) => f.buildTime.median);
  const outputSizes = fws.map((f) => f.outputSize);
  const pageWeights = fws.map((f) => avgPageWeight(f.pageWeight));

  const buildWin = pickLowest(buildMedians, true);
  const outputWin = pickLowest(outputSizes, true);
  const weightWin = pickLowest(pageWeights, true);

  const headerRow = `| Metric          | ${headerNames.join(' | ')} |`;
  const sepCols = headerNames.map(() => '---').join(' | ');
  const sepRow = `|-----------------|${sepCols}|`;
  const buildRow = `| Build time      | ${buildMedians
    .map((v, i) => bold(fmtMs(v), i === buildWin))
    .join(' | ')} |`;
  const outRow = `| Output size     | ${outputSizes
    .map((v, i) => bold(fmtBytes(v), i === outputWin))
    .join(' | ')} |`;
  const wtRow = `| Avg page weight | ${pageWeights
    .map((v, i) => bold(`${fmtBytes(v)} gzip`, i === weightWin))
    .join(' | ')} |`;

  const cpu = meta.cpuModel ?? 'unknown CPU';
  const node = meta.nodeVersion ?? 'unknown Node';
  const date = (meta.timestamp ?? '').slice(0, 10);

  return [
    BEGIN,
    '',
    headerRow,
    sepRow,
    buildRow,
    outRow,
    wtRow,
    '',
    `> Auto-generated by \`scripts/update-readme-bench.mjs\` from \`benchmarks/results/latest.json\`.`,
    `> Measured on ${cpu}, Node ${node}${date ? ` (${date})` : ''}. Run \`pnpm bench:cross\` to reproduce.`,
    `> See [litro.dev/benchmarks](https://litro.dev/benchmarks) for full results including TTFB, Lighthouse, and streaming metrics.`,
    '',
    END,
  ].join('\n');
}

async function main() {
  const json = JSON.parse(await readFile(JSON_PATH, 'utf-8'));
  if (!Array.isArray(json.crossFramework) || json.crossFramework.length === 0) {
    console.error('[update-readme-bench] latest.json has no crossFramework data — skipping.');
    process.exit(0);
  }

  const block = renderTable(json.crossFramework, json.meta ?? {});
  const readme = await readFile(README_PATH, 'utf-8');

  const beginIdx = readme.indexOf(BEGIN);
  const endIdx = readme.indexOf(END);
  if (beginIdx === -1 || endIdx === -1 || endIdx < beginIdx) {
    console.error(
      `[update-readme-bench] Could not find BENCH:BEGIN / BENCH:END markers in README.md. ` +
        `Add them around the benchmark table to enable auto-generation.`,
    );
    process.exit(1);
  }

  const before = readme.slice(0, beginIdx);
  const after = readme.slice(endIdx + END.length);
  const next = before + block + after;

  if (next === readme) {
    console.log('[update-readme-bench] No change.');
    return;
  }

  await writeFile(README_PATH, next, 'utf-8');
  console.log('[update-readme-bench] README.md benchmark table updated.');
}

main().catch((err) => {
  console.error('[update-readme-bench]', err);
  process.exit(1);
});
