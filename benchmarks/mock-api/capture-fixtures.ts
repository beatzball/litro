/**
 * One-time script to capture HN API fixtures for deterministic benchmarks.
 * Run: tsx capture-fixtures.ts
 */
import { writeFile, mkdir } from 'node:fs/promises';
import { join } from 'node:path';

const API = 'https://hacker-news.firebaseio.com/v0';
const FIXTURES_DIR = join(import.meta.dirname, 'fixtures');
const SHARED_DIR = join(import.meta.dirname, '..', 'apps', 'hn-shared');

const STORY_LIMIT = 30;
const COMMENT_DEPTH = 2;
const COMMENTS_PER_STORY = 20;

async function fetchJson<T>(path: string): Promise<T> {
  const res = await fetch(`${API}/${path}`);
  if (!res.ok) throw new Error(`${res.status} ${path}`);
  return res.json() as Promise<T>;
}

async function saveJson(dir: string, filename: string, data: unknown): Promise<void> {
  await writeFile(join(dir, filename), JSON.stringify(data, null, 2));
}

interface Item {
  id: number;
  by?: string;
  kids?: number[];
  type?: string;
  [key: string]: unknown;
}

async function captureComments(
  itemIds: number[],
  depth: number,
  itemsDir: string,
  capturedItems: Set<number>,
  capturedUsers: Set<string>,
): Promise<void> {
  if (depth <= 0 || itemIds.length === 0) return;

  const nextKids: number[] = [];

  for (const id of itemIds.slice(0, COMMENTS_PER_STORY)) {
    if (capturedItems.has(id)) continue;
    try {
      const item = await fetchJson<Item>(`item/${id}.json`);
      if (!item) continue;
      capturedItems.add(id);
      await saveJson(itemsDir, `${id}.json`, item);

      if (item.by && !capturedUsers.has(item.by)) {
        capturedUsers.add(item.by);
      }
      if (item.kids?.length) {
        nextKids.push(...item.kids);
      }
    } catch (err) {
      console.warn(`  Skipping item ${id}: ${err}`);
    }
  }

  if (nextKids.length > 0) {
    await captureComments(nextKids, depth - 1, itemsDir, capturedItems, capturedUsers);
  }
}

async function main(): Promise<void> {
  const itemsDir = join(FIXTURES_DIR, 'items');
  const usersDir = join(FIXTURES_DIR, 'users');
  await mkdir(itemsDir, { recursive: true });
  await mkdir(usersDir, { recursive: true });

  const capturedItems = new Set<number>();
  const capturedUsers = new Set<string>();
  const storyIds: { top: number[]; ask: number[]; show: number[] } = {
    top: [],
    ask: [],
    show: [],
  };

  // Fetch story ID lists
  console.log('Fetching story lists...');
  for (const [key, endpoint] of [
    ['top', 'topstories.json'],
    ['ask', 'askstories.json'],
    ['show', 'showstories.json'],
  ] as const) {
    const ids = await fetchJson<number[]>(endpoint);
    const limited = ids.slice(0, STORY_LIMIT);
    storyIds[key] = limited;
    await saveJson(FIXTURES_DIR, endpoint, limited);
    console.log(`  ${key}: ${limited.length} stories`);
  }

  // Fetch all unique stories
  const allStoryIds = [...new Set([...storyIds.top, ...storyIds.ask, ...storyIds.show])];
  console.log(`\nFetching ${allStoryIds.length} unique stories...`);

  for (const id of allStoryIds) {
    if (capturedItems.has(id)) continue;
    try {
      const item = await fetchJson<Item>(`item/${id}.json`);
      if (!item) continue;
      capturedItems.add(id);
      await saveJson(itemsDir, `${id}.json`, item);

      if (item.by && !capturedUsers.has(item.by)) {
        capturedUsers.add(item.by);
      }

      // Capture comment trees
      if (item.kids?.length) {
        await captureComments(item.kids, COMMENT_DEPTH, itemsDir, capturedItems, capturedUsers);
      }
    } catch (err) {
      console.warn(`  Skipping story ${id}: ${err}`);
    }
  }

  console.log(`\nCaptured ${capturedItems.size} items`);

  // Fetch users
  console.log(`Fetching ${capturedUsers.size} users...`);
  const userIds: string[] = [];
  for (const userId of capturedUsers) {
    try {
      const user = await fetchJson<{ id: string }>(`user/${userId}.json`);
      if (user) {
        await saveJson(usersDir, `${userId}.json`, user);
        userIds.push(userId);
      }
    } catch (err) {
      console.warn(`  Skipping user ${userId}: ${err}`);
    }
  }
  console.log(`  Saved ${userIds.length} users`);

  // Generate fixture-ids.ts for apps to import
  const fixtureIds = `// Auto-generated by capture-fixtures.ts — do not edit
export const topStoryIds = ${JSON.stringify(storyIds.top)} as const;
export const askStoryIds = ${JSON.stringify(storyIds.ask)} as const;
export const showStoryIds = ${JSON.stringify(storyIds.show)} as const;
export const userIds = ${JSON.stringify(userIds.slice(0, 10))} as const;
`;
  await writeFile(join(SHARED_DIR, 'fixture-ids.ts'), fixtureIds);
  console.log(`\nGenerated fixture-ids.ts with ${storyIds.top.length} top, ${storyIds.ask.length} ask, ${storyIds.show.length} show story IDs, ${userIds.slice(0, 10).length} user IDs`);

  console.log('\nDone!');
}

main().catch(err => {
  console.error(err);
  process.exit(1);
});
